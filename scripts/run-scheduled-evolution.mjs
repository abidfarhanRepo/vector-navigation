#!/usr/bin/env node
// run-scheduled-evolution.mjs — the unattended wrapper around the evolution cycle
// (ticket 12).
//
// `run-evolution-cycle.mjs` does the work; this makes it safe to run from a
// scheduler and impossible to fail silently. It mirrors `run-scheduled-ci.mjs`
// deliberately — same reports/ convention, same staleness alarm — because the
// lesson that produced that design was a gate going dark for nine nights while
// every dashboard still looked plausible.
//
// Four things this adds over calling the cycle directly:
//
//   1. **A lock.** The full-Qatar batch is not instant, and two cycles sharing one
//      watermark would double-process or skip. A stale lock (older than
//      LOCK_STALE_H) is broken rather than deadlocking the schedule forever.
//   2. **A report, always.** Success, failure, skipped-because-locked — every
//      outcome writes reports/evolution-<stamp>.log and evolution-latest.md.
//      "No report" is the one outcome that must never happen, because it is
//      indistinguishable from "nobody looked".
//   3. **A staleness banner** in evolution-latest.md when the previous report is
//      older than STALE_HOURS. The file everything else reads says so itself.
//   4. **An honest exit code.** Non-zero only for a real stage failure; stages
//      that skip because their inputs are absent are the correct behaviour of a
//      system that has collected nothing, and must not page anyone.
//
//   node scripts/run-scheduled-evolution.mjs

import { spawn } from 'node:child_process';
import {
  existsSync, mkdirSync, readFileSync, readdirSync, statSync, unlinkSync, writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPORTS_DIR = join(ROOT, 'reports');
const LOCK_PATH = join(ROOT, '.evolution-cycle.lock');
const LATEST = join(REPORTS_DIR, 'evolution-latest.md');

// A cycle over the full Qatar network takes minutes, not hours; anything holding
// the lock this long has died without releasing it.
const LOCK_STALE_H = 6;
// Daily cadence, so a gap beyond this means the schedule itself has stopped.
const STALE_HOURS = 36;

const stamp = new Date().toISOString().replace(/[:.]/g, '-').replace('T', '_').slice(0, 19);
const logPath = join(REPORTS_DIR, `evolution-${stamp}.log`);

function previousReportAgeH() {
  try {
    const logs = readdirSync(REPORTS_DIR)
      .filter((n) => n.startsWith('evolution-') && n.endsWith('.log'))
      .sort();
    if (logs.length === 0) return Infinity;
    const newest = logs[logs.length - 1];
    return (Date.now() - statSync(join(REPORTS_DIR, newest)).mtimeMs) / 3600000;
  } catch {
    return Infinity;
  }
}

function writeReport({ status, exitCode, summary, body }) {
  if (!existsSync(REPORTS_DIR)) mkdirSync(REPORTS_DIR, { recursive: true });
  writeFileSync(
    logPath,
    `# Vector scheduled evolution cycle\n# ${new Date().toISOString()}\n` +
      `# status=${status} exit=${exitCode}\n\n${body}\n`,
    'utf8',
  );

  const ageH = previousReportAgeH();
  const staleMsg =
    ageH > STALE_HOURS
      ? `**STALE — no evolution report for ${ageH === Infinity ? 'ever' : `> ${STALE_HOURS} h`}.** ` +
        `If this line shows, the cycle is not running on schedule.\n\n`
      : '';

  writeFileSync(
    LATEST,
    `# Latest Vector evolution cycle\n\n${staleMsg}` +
      `- **Run (UTC):** ${new Date().toISOString()}\n` +
      `- **Status:** ${status}\n` +
      `- **Summary:** ${summary}\n` +
      `- **Full log:** reports/evolution-${stamp}.log\n` +
      `- **Dashboard:** /evolution (regenerated by this run)\n`,
    'utf8',
  );
}

// ---- lock ----------------------------------------------------------------

function acquireLock() {
  if (existsSync(LOCK_PATH)) {
    let ageH = Infinity;
    let holder = 'unknown';
    try {
      ageH = (Date.now() - statSync(LOCK_PATH).mtimeMs) / 3600000;
      holder = readFileSync(LOCK_PATH, 'utf8').trim();
    } catch {
      /* treat an unreadable lock as stale */
    }
    if (ageH < LOCK_STALE_H) {
      return { ok: false, holder, ageH };
    }
    // Stale: a previous run died without releasing. Break it rather than let one
    // crash disable the schedule permanently.
    console.error(
      `[lock] breaking a stale lock (${ageH.toFixed(1)} h old, holder: ${holder})`,
    );
    try {
      unlinkSync(LOCK_PATH);
    } catch {
      /* raced with another breaker; the write below decides the winner */
    }
  }
  writeFileSync(LOCK_PATH, `pid=${process.pid} started=${new Date().toISOString()}\n`, 'utf8');
  return { ok: true };
}

function releaseLock() {
  try {
    unlinkSync(LOCK_PATH);
  } catch {
    /* already gone */
  }
}

// ---- run -----------------------------------------------------------------

const lock = acquireLock();
if (!lock.ok) {
  const why =
    `SKIPPED: another evolution cycle has been running for ${lock.ageH.toFixed(1)} h ` +
    `(${lock.holder}). Two cycles over one watermark would double-process or skip ` +
    `observations, so this run declined to start.`;
  console.error(why);
  writeReport({ status: 'SKIPPED-LOCKED', exitCode: 0, summary: 'another cycle still running', body: why });
  // Not a failure: the schedule behaved correctly. Exit 0 so it does not page.
  process.exit(0);
}

let out = '';
const child = spawn(process.execPath, [join(ROOT, 'scripts', 'run-evolution-cycle.mjs')], {
  cwd: ROOT,
  windowsHide: true,
});
const collect = (d) => {
  const text = d.toString();
  out += text;
  process.stdout.write(text);
};
child.stdout.on('data', collect);
child.stderr.on('data', collect);

child.on('error', (err) => {
  releaseLock();
  const why = `FAIL: could not launch run-evolution-cycle.mjs: ${err.message}`;
  console.error(why);
  writeReport({ status: 'FAIL', exitCode: 1, summary: 'runner would not launch', body: out + '\n' + why });
  process.exit(1);
});

child.on('close', (code) => {
  releaseLock();
  const exitCode = code ?? 1;
  const status = exitCode === 0 ? 'PASS' : 'FAIL';

  // Pull the cycle's own one-line summary out of its output so the report is
  // readable without opening the log.
  const summaryLine =
    out.split('\n').reverse().find((l) => l.startsWith('summary:')) ?? 'no summary emitted';
  const coverage = out.split('\n').find((l) => l.startsWith('coverage:')) ?? '';
  const eta = out.split('\n').find((l) => l.startsWith('eta:')) ?? '';

  writeReport({
    status,
    exitCode,
    summary: [summaryLine, coverage, eta].filter(Boolean).join(' | '),
    body: out,
  });

  console.log(`Scheduled evolution cycle finished: ${status} (exit ${exitCode}). Report: ${logPath}`);
  process.exit(exitCode === 0 ? 0 : 1);
});
